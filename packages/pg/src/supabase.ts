/**
 * TLS policy for a Supabase connection string: verify Supabase hosts against the
 * pinned root CA; leave anything else (local docker, CI service) to the URL.
 * Plug it in as `PoolEnvConfig.ssl`.
 */
export function supabaseSsl(connectionString: string): { ca: string } | undefined {
  const { hostname } = new URL(connectionString)
  return hostname.endsWith('.supabase.com') || hostname.endsWith('.supabase.co')
    ? { ca: SUPABASE_ROOT_CA_2021 }
    : undefined
}

const URL_SSL_PARAMS = ['ssl', 'sslmode', 'sslcert', 'sslkey', 'sslrootcert', 'uselibpqcompat']

/**
 * Drop the TLS query params from a connection string. `pg` lets URL params
 * override the `ssl` object, so when a TLS resolver (e.g. `supabaseSsl`) owns the
 * policy, a provider-supplied `?sslmode=require` (the Supabase/Vercel integration
 * adds it) would silently discard the pinned CA. Other params are kept.
 */
export function stripSslParams(connectionString: string): string {
  const url = new URL(connectionString)
  for (const param of URL_SSL_PARAMS) url.searchParams.delete(param)
  return url.toString()
}
